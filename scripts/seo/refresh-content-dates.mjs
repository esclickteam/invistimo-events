  "/seating-explained": ["app/seating-explained"],
  "/event-management": ["app/event-management", "app/components/event/EventManagementPage.jsx"],
  "/pricing": ["app/pricing"],
  "/faq": ["app/faq", "lib/seo/faq"],
  "/info/about": ["app/(marketing)/info/about"],
