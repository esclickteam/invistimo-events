export function getPlate(id: string) {
  return STUDIO_PLATES.find((item) => item.id === id) || null;
}

export function freezePlate(
  plateDef: StudioPlate,
  details?: Partial<InvitationDetails>
): StudioSnapshot {
  const nextDetails = sanitizeDetails(details, plateDef.details);
  return {
    capturedAt: new Date().toISOString(),
    templateId: plateDef.id,
    templateVersion: 2,
    name: plateDef.name,
    category: plateDef.category,
    style: plateDef.style,
    free: plateDef.free,
    width: 1080,
    height: 1920,
    motion: plateDef.animation === "none" ? "none" : "soft",
    formats: { static: true, digital: true, animated: plateDef.animation !== "none", video: plateDef.animation !== "none" },
    background: "solid",
    palette: {
      paper: "#ffffff",
      ink: plateDef.ink,
      accent: plateDef.accent,
      muted: plateDef.muted,
      deep: plateDef.ink,
    },
    layers: [],
    content: {
      ...emptyContent(),
      hostNames: [nextDetails.brideName, nextDetails.groomName].filter(Boolean).join(" ו"),
      wording: nextDetails.opening,
      hebrewDate: nextDetails.hebrewDate,
      gregorianDate: nextDetails.gregorianDate,
      receptionTime: nextDetails.reception,
      ceremonyTime: nextDetails.ceremony,
      venueName: nextDetails.venue,
      venueAddress: nextDetails.address,
      guestGreeting: nextDetails.guestGreeting,
    },
    layerOverrides: {},
    images: {},
    personalGreeting: true,
    music: plateDef.defaultMusic
      ? libraryMusic(plateDef.animation === "floral" || plateDef.animation === "zoom" ? "start" : "names")
      : undefined,
    plate: {
      id: plateDef.id,
      art: plateDef.art,
      animation: plateDef.animation,
      durationMs: plateDef.durationMs,
      ink: plateDef.ink,
      muted: plateDef.muted,
      accent: plateDef.accent,
      nameFont: plateDef.nameFont,
      textFont: plateDef.textFont,
      nameSize: plateDef.nameSize,
      inset: { ...plateDef.inset },
      medallion: plateDef.medallion,
      details: nextDetails,
      speed: 1,
    },
  };
}

export function applyPlateChrome(snapshot: StudioSnapshot, plateDef: StudioPlate) {
  const details = snapshot.plate?.details || plateDef.details;
  const next = freezePlate(plateDef, details);
  if (snapshot.music) next.music = snapshot.music;
  if (snapshot.plate?.speed) next.plate!.speed = snapshot.plate.speed;
  return next;
}

